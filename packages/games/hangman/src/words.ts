/** Normalisiert ein deutsches Wort in Großbuchstaben (`ß` -> `SS`). */
export function normalizeWord(word: string): string {
  return word.replace(/ß/g, 'SS').replace(/ẞ/g, 'SS').toUpperCase().trim();
}

/** Prüft, ob ein Zeichen ein zu ratender Buchstabe aus dem Alphabet ist. */
export function isGuessableChar(ch: string): boolean {
  return ALPHABET.includes(ch);
}

/** Maskiert alle noch nicht geratenen Buchstaben eines normalisierten Wortes mit `_`. */
export function maskWord(normalizedWord: string, guessedLetters: readonly string[]): string {
  const guessedSet = new Set(guessedLetters);
  return [...normalizedWord]
    .map((ch) => (isGuessableChar(ch) ? (guessedSet.has(ch) ? ch : '_') : ch))
    .join('');
}

/** Prüft, ob alle Buchstaben des Wortes bereits geraten wurden. */
export function isWordSolved(normalizedWord: string, guessedLetters: readonly string[]): boolean {
  const guessedSet = new Set(guessedLetters);
  for (const ch of normalizedWord) {
    if (isGuessableChar(ch) && !guessedSet.has(ch)) return false;
  }
  return true;
}

