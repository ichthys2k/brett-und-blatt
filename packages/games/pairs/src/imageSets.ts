export interface PairEntry {
  a: string;
  b: string;
  /** Optionaler Bildschlüssel für die UI (wird über `setPairImageResolver` aufgelöst). */
  image?: string;
  /** Gesprochener Name, wenn `a`/`b` nur ein Emoji sind. */
  label?: string;
}

export interface PairSet {
  id: string;
  name: string;
  group?: string;
  pairs: PairEntry[];
}

type QuartettRaw = { id: string; name: string; cards: { name: string; image?: string }[] };

function fromQuartett(raw: QuartettRaw, name: string): PairSet {
  return {
    id: `quartett-${raw.id}`,
    name,
    group: 'Quartett',
    pairs: raw.cards.map((card) => ({
      a: card.name,
      b: card.name,
      image: card.image ? `quartett:${raw.id}/${card.image}` : undefined,
    })),
  };
}

function samePairs(items: readonly [image: string, name: string][]): PairEntry[] {
  return items.map(([image, name]) => ({ a: name, b: name, image }));
}

