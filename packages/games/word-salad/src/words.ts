export type SaladCategory = 'mix' | 'natur' | 'mathe';

export interface StemEntry {
  /** Schöne Anzeige-Schreibweise (z. B. "Sonnenblume"). */
  display: string;
  /** Kurzer Hinweis / Themenbereich. */
  hint: string;
  /** Kuratierte Teilwörter für dieses Stammwort. */
  subwords: readonly string[];
}

/**
 * Normalisiert ein deutsches Wort auf Großbuchstaben (`ß` -> `SS`) und entfernt Leerzeichen/Bindestriche.
 */
export function normalizeSaladWord(raw: string): string {
  return raw
    .trim()
    .replace(/ß/g, 'SS')
    .replace(/ẞ/g, 'SS')
    .toUpperCase()
    .replace(/[^A-ZÄÖÜ]/g, '');
}

/**
 * Prüft, ob `candidate` (bereits normalisiert) ausschließlich aus den Buchstaben von `stem` (bereits normalisiert)
 * gebildet werden kann, wobei jeder Buchstabe höchstens so oft genutzt werden darf wie in `stem`.
 */
export function canFormFromStem(candidateNorm: string, stemNorm: string, minLength = 3): boolean {
  if (candidateNorm.length < minLength) return false;
  if (candidateNorm.length > stemNorm.length) return false;
  if (candidateNorm === stemNorm) return false;

  const counts = new Map<string, number>();
  for (const ch of stemNorm) {
    counts.set(ch, (counts.get(ch) ?? 0) + 1);
  }
  for (const ch of candidateNorm) {
    const rem = counts.get(ch) ?? 0;
    if (rem <= 0) return false;
    counts.set(ch, rem - 1);
  }
  return true;
}

/**
 * Berechnet den Basis-Punktwert eines gefundenen Teilwortes anhand seiner Buchstabenlänge.
 */
export function scoreWordLength(length: number): number {
  if (length <= 2) return 0;
  if (length === 3) return 1;
  if (length === 4) return 2;
  if (length === 5) return 4;
  if (length === 6) return 7;
  return 11;
}

