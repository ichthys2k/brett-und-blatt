/**
 * Liefert alle gültigen deutschen Teilwörter für ein gegebenes Stammwort (`stemDisplayOrNorm`),
 * sortiert nach Länge (absteigend) und alphabetisch.
 */
export function getValidSubwords(stemDisplayOrNorm: string, minLength = 3): string[] {
  const stemNorm = normalizeSaladWord(stemDisplayOrNorm);
  const valid: string[] = [];
  for (const word of GLOBAL_WORD_SET) {
    if (canFormFromStem(word, stemNorm, minLength)) {
      valid.push(word);
    }
  }
  return valid.sort((a, b) => b.length - a.length || a.localeCompare(b, 'de'));
}
